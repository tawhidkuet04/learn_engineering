/**
 * Vitest global setup: prints the versions under test, and after the run
 * merges verify/results/*.json into the site's badge data and a report.
 */
import { readdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { haproxyVersion, nginxVersion, redisVersion } from './procs';
import { RESULTS_DIR, type ResultFile } from './results';

const ROOT = path.resolve(import.meta.dirname, '..', '..');
const VERIFIED = path.join(ROOT, 'src', 'content', 'verified.json');
const CHECKS = path.join(ROOT, 'src', 'content', 'checks.json');
const REPORT = path.join(ROOT, 'verify', 'REPORT.md');

export function setup() {
  console.log(`\nChecking lessons against nginx ${nginxVersion()}, HAProxy ${haproxyVersion()}, Redis ${redisVersion()}\n`);
}

function writeAtomic(file: string, text: string) {
  const tmp = `${file}.${process.pid}.tmp`;
  writeFileSync(tmp, text);
  renameSync(tmp, file);
}

export function teardown() {
  const files: ResultFile[] = readdirSync(RESULTS_DIR)
    .filter((f) => f.endsWith('.json'))
    .sort()
    .flatMap((f) => {
      try {
        return [JSON.parse(readFileSync(path.join(RESULTS_DIR, f), 'utf8')) as ResultFile];
      } catch {
        console.warn(`skipping unreadable results file ${f}`);
        return [];
      }
    });

  // Badge data: snippet fingerprint -> what checked it.
  const snippets: Record<string, { by: string; note: string; kind: 'loads' | 'ran' }[]> = {};
  for (const f of files) {
    for (const s of f.stamps) {
      const list = (snippets[s.hash] ??= []);
      if (!list.some((x) => x.by === s.by && x.note === s.note)) list.push({ by: s.by, note: s.note, kind: s.kind });
    }
  }
  const sorted = Object.fromEntries(Object.entries(snippets).sort(([a], [b]) => a.localeCompare(b)));
  writeAtomic(VERIFIED, `${JSON.stringify({ snippets: sorted }, null, 1)}\n`);

  // Every comparison, for the site's /tested page.
  const checks = files.flatMap((f) => f.checks.map((c) => ({ ...c, file: f.file })));
  const forSite = checks.map(({ lesson, step, title, software, real, lesson_says, pass }) => ({ lesson, step, title, software, real, lesson_says, pass }));
  writeAtomic(CHECKS, `${JSON.stringify({ ran: new Date().toISOString().slice(0, 10), checks: forSite }, null, 1)}\n`);

  // Human-readable report, grouped by lesson.
  const lessons = [...new Set(checks.map((c) => c.lesson))].sort();
  const failed = checks.filter((c) => !c.pass).length;
  const lines = [
    '# Lessons vs. real software',
    '',
    'Generated by `npm run verify`. Each row ran a lesson scenario or config against the real program and compared the result with what the lesson shows.',
    '',
    `${checks.length} checks, ${failed ? `**${failed} disagree**` : 'all agree'}. ${Object.keys(sorted).length} code snippets carry a "tested" badge.`,
    '',
  ];
  for (const lesson of lessons) {
    lines.push(`## ${lesson}`, '', '| | Check | Real software | What it did | Lesson says |', '|---|---|---|---|---|');
    for (const c of checks.filter((x) => x.lesson === lesson)) {
      const cell = (s?: string) => (s ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ');
      lines.push(`| ${c.pass ? '✓' : '✗'} | ${cell(c.title)}${c.step ? ` (\`${c.step}\`)` : ''} | ${cell(c.software)} | ${cell(c.real)} | ${cell(c.lesson_says)} |`);
    }
    lines.push('');
  }
  writeAtomic(REPORT, `${lines.join('\n')}\n`);
}
